/**
 * `twentyfirst-ui theme <source>`: writes a theme for the kit and imports it after the kit styles.
 *
 * The source is a preset name (`blue`, `violet`, …), a brand colour (`#2563eb`, light and
 * optionally dark: `#2563eb,#60a5fa`), or a CSS file with a shadcn theme (ui.shadcn.com/themes,
 * tweakcn): `:root { --primary: … }` and `.dark { … }`.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { detect } from "./project.js";
import {
  THEME_PRESETS,
  brandTheme,
  parseThemeCss,
  themeCss,
  type ThemeInput,
} from "./shared/theme.js";
import { readConfig, read, write, type Kit, type Logger } from "./util.js";

export interface ThemeOptions {
  cwd: string;
  source: string;
  kit?: Kit;
  /** Both kits loaded (themes.css): write the theme for both, scoped by data-kit. */
  both?: boolean;
  /** Where to write the theme; default: theme.css next to the app's stylesheet. */
  out?: string;
  log: Logger;
}

export function resolveTheme(source: string, cwd: string): { name: string; theme: ThemeInput } {
  const preset = THEME_PRESETS[source.toLowerCase()];
  if (preset) return { name: `${preset.label} preset`, theme: preset.theme };
  const colours = source.split(",").map((s) => s.trim());
  if (colours.every((c) => /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.test(c)))
    return { name: `brand colour ${source}`, theme: brandTheme(colours[0] as string, colours[1]) };
  const file = resolve(cwd, source);
  if (existsSync(file)) {
    const theme = parseThemeCss(readFileSync(file, "utf8"));
    if (!theme.light && !theme.dark && !theme.radius)
      throw new Error(`${source} has no theme variables (:root { --primary: … } and .dark { … })`);
    return { name: relative(cwd, file), theme };
  }
  throw new Error(
    `"${source}" is not a preset (${Object.keys(THEME_PRESETS).join(", ")}), a hex colour or a CSS file`,
  );
}

export function theme(o: ThemeOptions): string {
  const config = readConfig(o.cwd);
  const kit: Kit = o.kit ?? config?.kit ?? "halo";
  const both = o.both ?? !!config?.both;
  const { name, theme: input } = resolveTheme(o.source, o.cwd);
  const p = detect(o.cwd);
  const sheet = config?.css ? join(o.cwd, config.css) : p.css;
  const out = o.out
    ? resolve(o.cwd, o.out)
    : join(sheet ? dirname(sheet) : join(o.cwd, p.srcDir ? "src/app" : "app"), "theme.css");
  const kits: Kit[] = both ? ["halo", "pro"] : [kit];
  const css =
    `/* Twentyfirst UI theme from ${name}. Generated by twentyfirst-ui theme; edit freely. */\n` +
    kits.map((k) => themeCss(input, { kit: k, scoped: both })).join("\n");
  write(out, css);
  o.log.log(`${relative(o.cwd, out)}: theme for ${both ? "both kits" : kit} (${name})`);

  // import it once, after the kit styles so it wins on order too
  if (sheet) {
    const text = read(sheet) ?? "";
    const rel = relative(dirname(sheet), out).replace(/\\/g, "/");
    const spec = rel.startsWith(".") ? rel : `./${rel}`;
    if (!text.includes(spec)) {
      const lines = text.split("\n");
      let last = -1;
      lines.forEach((l, i) => {
        if (/^\s*@import\b/.test(l)) last = i;
      });
      lines.splice(last + 1, 0, `@import "${spec}";`);
      write(sheet, lines.join("\n"));
      o.log.log(`${relative(o.cwd, sheet)}: imports ${spec}`);
    }
  } else o.log.log(`Import ${relative(o.cwd, out)} once, after the kit's styles.css.`);
  return out;
}
